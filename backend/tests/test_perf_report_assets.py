REPORT_FULL = """<!DOCTYPE html>
<html><head>
<script src="https://resources.modelscope.cn/third-part/js/plotly/plotly-2.35.2.min.js"></script>
</head><body>
<h2>Basic Information</h2>
<table><tr><td>Total Requests</td><td>400</td></tr></table>
<div id="chart-latency" class="plotly-graph-div" style="height:100%; width:100%;"></div>
<script>
  window.PLOTLYENV=window.PLOTLYENV || {};
  Plotly.newPlot("chart-latency", [{y:[1,2,3]}], {});
</script>
<div id="req-latency-p1" class="plotly-graph-div"></div>
<script>
  window.PLOTLYENV=window.PLOTLYENV || {};
  Plotly.newPlot("req-latency-p1", [{y:[4,5]}], {});
</script>
<table><tr><td>50%</td><td>3.03</td></tr></table>
<footer>Generated by EvalScope</footer>
</body></html>
"""


def test_strip_charts_removes_plotly_and_charts():
    out, removed = assets.strip_charts(REPORT_FULL)
    assert removed == 2
    assert "plotly-2.35.2.min.js" not in out
    assert "Plotly.newPlot" not in out
    assert "PLOTLYENV" not in out


def test_strip_charts_keeps_tables():
    out, _ = assets.strip_charts(REPORT_FULL)
    assert "Total Requests" in out
    assert "400" in out
    assert "50%" in out
    assert "Generated by EvalScope" in out


def test_strip_charts_leaves_placeholder():
    out, _ = assets.strip_charts(REPORT_FULL)
    assert out.count("图表已省略") == 2


def test_strip_charts_keeps_unrelated_scripts():
    html = REPORT_FULL.replace(
        "<footer>", '<script>var keep=1;</script><footer>'
    )
    out, _ = assets.strip_charts(html)
    assert "var keep=1" in out


def test_strip_charts_significantly_shrinks_output():
    heavy = REPORT_FULL.replace(
        "<footer>", "<script>" + ("x" * 200000) + "</script><footer>"
    )
    out, _ = assets.strip_charts(heavy)
    # 图表脚本被移除，仅保留无关脚本
    assert len(out) < len(heavy)


def test_strip_charts_on_report_without_charts():
    html = "<html><body><table><tr><td>a</td></tr></table></body></html>"
    out, removed = assets.strip_charts(html)
    assert removed == 0
    assert out == html
