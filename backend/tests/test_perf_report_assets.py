"""压测报告离线化（Plotly 内联）测试。

背景：EvalScope 的 HTML 报告从 modelscope CDN 外链加载 3.5MB 的 Plotly，
内网环境下浏览器会长时间卡住。平台在下载报告时把 Plotly 内联进去，
让用户拿到自包含文件。

这些测试验证：
  * 外链能被准确识别并替换（属性顺序 / 引号风格都要兼容）
  * 库源码里的 </script> 不会提前闭合标签
  * 没有缓存/没有外链时安全降级
"""
import pytest

from app.services import perf_report_assets as assets


REPORT_WITH_CDN = """<!DOCTYPE html>
<html><head>
<script src="https://resources.modelscope.cn/third-part/js/plotly/plotly-2.35.2.min.js"></script>
</head><body>
<div id="chart"></div>
<script>Plotly.newPlot('chart', []);</script>
</body></html>
"""


def test_replaces_plotly_cdn_with_inline_script():
    html, ok = assets.inline_plotly(REPORT_WITH_CDN, "var Plotly={};")
    assert ok is True
    assert "resources.modelscope.cn" not in html
    assert "<script>var Plotly={};</script>" in html
    # 报告自身的脚本保留
    assert "Plotly.newPlot" in html


@pytest.mark.parametrize(
    "tag",
    [
        '<script src="https://x/plotly.min.js"></script>',
        "<script src='https://x/plotly.min.js'></script>",
        '<script  type="text/javascript"  src="https://x/plotly.min.js" ></script>',
        '<script defer src="https://x/plotly-2.35.2.min.js"></script>',
        '<SCRIPT SRC="https://x/plotly.min.js"></SCRIPT>',
    ],
)
def test_tag_variants_are_matched(tag):
    html = f"<html><head>{tag}</head><body>x</body></html>"
    out, ok = assets.inline_plotly(html, "LIB")
    assert ok is True
    assert "LIB" in out
    assert "plotly.min.js" not in out


def test_escapes_closing_script_in_library_source():
    """库源码里若含 </script> 会提前闭合标签，导致报告白屏。"""
    out, ok = assets.inline_plotly(REPORT_WITH_CDN, 'var x="</script>";')
    assert ok is True
    assert out.count("</script>") == REPORT_WITH_CDN.count("</script>")
    assert "<\\/script>" in out


def test_returns_unchanged_when_no_plotly_source():
    out, ok = assets.inline_plotly(REPORT_WITH_CDN, None)
    assert ok is False
    assert out == REPORT_WITH_CDN


def test_returns_unchanged_when_no_external_tag():
    html = "<html><body><script>var a=1;</script></body></html>"
    out, ok = assets.inline_plotly(html, "LIB")
    assert ok is False
    assert out == html


def test_only_first_tag_is_replaced():
    html = (
        '<script src="https://a/plotly.min.js"></script>'
        '<script src="https://b/plotly.min.js"></script>'
    )
    out, ok = assets.inline_plotly(html, "LIB")
    assert ok is True
    assert out.count("LIB") == 1
    assert "https://b/plotly.min.js" in out


def test_prepare_report_html_uses_cache_only(tmp_path, monkeypatch):
    """无缓存时不应触发网络请求，直接原样返回。"""
    monkeypatch.setattr(assets.settings, "perf_outputs_dir", str(tmp_path))
    out, ok = assets.prepare_report_html(REPORT_WITH_CDN)
    assert ok is False
    assert out == REPORT_WITH_CDN


def test_prepare_report_html_inlines_from_cache(tmp_path, monkeypatch):
    monkeypatch.setattr(assets.settings, "perf_outputs_dir", str(tmp_path))
    cache = tmp_path / ".assets"
    cache.mkdir(parents=True)
    (cache / assets.PLOTLY_FILENAME).write_text("var Plotly={cached:1};" * 40000, encoding="utf-8")

    out, ok = assets.prepare_report_html(REPORT_WITH_CDN)
    assert ok is True
    assert "resources.modelscope.cn" not in out


def test_read_cache_ignores_truncated_file(tmp_path, monkeypatch):
    """下载中断留下的残片不能被当成有效缓存。"""
    monkeypatch.setattr(assets.settings, "perf_outputs_dir", str(tmp_path))
    cache = tmp_path / ".assets"
    cache.mkdir(parents=True)
    (cache / assets.PLOTLY_FILENAME).write_text("partial", encoding="utf-8")
    assert assets._read_cache() is None


